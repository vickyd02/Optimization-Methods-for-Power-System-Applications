import cvxpy as cp
import numpy as np
import time

# Define f and gradient g
def f(x):
    return (x-4)**2 + 7

def g(x):
    return 2*x - 8

# Bounds
x_low, x_high = -12, 11
tolerance = 0.0004

# --- Initialize ---
x_init = x_low
constraints_list = []  # will store (f(xi), g(xi), xi) tuples

# Add initial cutting plane at x = -0.5
constraints_list.append((f(x_init), g(x_init), x_init))

# Initialize bounds
upper_bound = f(x_init)
lower_bound = -10000.0

print(f"{'Iter':>4} | {'x*':>8} | {'theta*':>10} | {'UB':>10} | {'LB':>12} | {'UB-LB':>12}")
print("-" * 70)

start_time = time.process_time()
for iteration in range(1, 1000):
    # --- Define CVXPY problem ---
    x = cp.Variable()
    theta = cp.Variable()

    # Bound constraints on x
    cvxpy_constraints = [x >= x_low, x <= x_high]

    # Add all cutting plane constraints: theta >= f(xi) + g(xi)*(x - xi)
    for (fi, gi, xi) in constraints_list:
        cvxpy_constraints.append(theta >= fi + gi * (x - xi))

    # Solve
    prob = cp.Problem(cp.Minimize(theta), cvxpy_constraints)
    prob.solve(solver=cp.HIGHS)

    x_star = x.value
    theta_star = theta.value

    # Update bounds
    lower_bound = theta_star          # LP gives a valid lower bound
    upper_bound = min(upper_bound, f(x_star))  # best true f value seen so far

    print(f"{iteration:>4} | {x_star:>8.4f} | {theta_star:>10.4f} | {upper_bound:>10.4f} | {lower_bound:>12.4f} | {upper_bound - lower_bound:>12.6f}")

    # --- Check convergence ---
    if upper_bound - lower_bound <= tolerance:
        print(f"\nConverged at iteration {iteration}!")
        print(f"Optimal x ≈ {x_star:.6f}")
        print(f"Optimal f(x) ≈ {f(x_star):.6f}")
        break

    # --- Add new cutting plane at x_star ---
    constraints_list.append((f(x_star), g(x_star), x_star))

