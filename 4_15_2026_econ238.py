# Define the function that finds f and g,
def oracle_squared_L2(x):
    """Returns f(x) = sum(x^2) and the exact gradient g(x) = 2x"""
    f_val = np.sum(x**2)
    g_val = 2.0 * x
    return f_val, g_val

def run_subgradient(n, x_low=-0.5, x_high=1.0, tol=1e-4, max_iter=5000):
    x = np.full(n, x_high) # Began at the upper bound
    #chose the upper bound because By starting at the upper bound, we are choosing the "worst-case" scenario
    #This will make the alogirthm travel a further distance
    #choosing the lower bound would arrive a tthe same result, only tolerance matters here
    #This is a form of stress testing by choosing the worst case scenario

    best_UB = float('inf')
    best_LB = float('-inf')

    UB_hist, LB_hist, gap_hist = [], [], []

    start_time = time.time()

    for k in range(1, max_iter + 1):
        f_val, g_val = oracle_squared_L2(x)

        # continously update the upper bound
        best_UB = min(best_UB, f_val)

        # calculate LB for the current tangent line
        x_extreme = np.where(g_val > 0, x_low, x_high)
        cut_min = f_val + np.dot(g_val, (x_extreme - x))
        best_LB = max(best_LB, cut_min)

        gap = best_UB - best_LB

        UB_hist.append(best_UB)
        LB_hist.append(best_LB)
        gap_hist.append(gap)

        # End if the optimality gap is reached
        if gap <= tol:
            break

        # subgradient step of 0.1 and projection
        #changing step size to a much bigger number like 1 could make it bounce back and forth
        #Step size less than 0.1 might be too small and take too many iterations to converge
        #We chose a step size that makes the most sense for our given range
        step_size = 0.1 / np.sqrt(k)  # traditional step size used in many subgrad problems
        x_raw = x - step_size * g_val
        x = np.clip(x_raw, x_low, x_high) #actual projection

    cpu_time = time.time() - start_time

    return best_UB, gap, k, cpu_time, UB_hist, LB_hist, gap_hist

