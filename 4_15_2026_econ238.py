print(f"{'iter':>4} | {'x_k':>8} | {'f(x_k)':>10} | {'f_best':>10} | {'||dx||':>10}")
print("-" * 60)

for iteration in range(1, 1000):
    alpha  = 1 / np.sqrt(iteration)
    gx     = g(x)
    x_new  = np.clip(x - alpha * gx, x_low, x_high)

    # ── stopping criterion: change in x ──────────────────────────────
    dx = np.linalg.norm(x_new - x)   # works for scalar or vector x

    if f(x_new) < fbest:
        bestx = x_new
        fbest = f(x_new)

    print(f"{iteration:>4} | {x_new:>8.4f} | {f(x_new):>10.4f} | {fbest:>10.4f} | {dx:>10.6f}")

    history.append((iteration, x_new, fbest, dx))
    x = x_new

    if dx <= tolerance:
        print(f"\nConverged at iteration {iteration}: ||dx|| = {dx:.6f} <= {tolerance}")
        break

