"""**Problem 6: Level Method with Applications to Question 4**


---

This is the application of the level method to problem 4 of the project. It is comparable to the Kelley method but addresses several key issues.

The level method is better in high dimensions because it:

1) Avoids extreme-point solutions (which is exactly what Kelley does by finding a global minimum)
2) Controls step size geometrically and finds the level set region from which it finds its next iteration solution
3) Uses the cutting-plane model locally, not globally
4) Maintains centrality, which is critical in high dimensions
5) Reduces sensitivity to model noise
"""

import cvxpy as cp
import numpy as np
import matplotlib.pyplot as plt
import pandas as pd
import time

def f(x):   return np.dot(x, x)
def g(x):   return 2 * x

dimensions  = [2, 5, 10, 100, 500]
results     = []
historysALL = {}
lam         = 0.05   # level parameter: 0=stay near UB, 1=push toward LB
tolerance   = 0.0001

for n in dimensions:
    print(f"\nRunning n = {n}...")
    x_low  = -0.5 * np.ones(n)
    x_high =  1 * np.ones(n)

    # ── start at corner, far from optimum ────────────────────────────
    x_cur   = x_low.copy()
    best_UB = f(x_cur)
    best_LB = -np.inf
    best_x  = x_cur.copy()

    cuts = [(f(x_cur), g(x_cur), x_cur.copy())]
    UB_hist, LB_hist, gap_hist = [], [], []

    start = time.time()

    for k in range(1, 1000):

        # ── Step 1: LP to update LB ───────────────────────────────────
        x_var  = cp.Variable(n)
        theta  = cp.Variable()
        lp_cons = [x_var >= x_low, x_var <= x_high]
        for (fi, gi, xi) in cuts:
            lp_cons.append(theta >= fi + gi @ (x_var - xi))

        cp.Problem(cp.Minimize(theta), lp_cons).solve(solver=cp.HIGHS)
        best_LB = max(best_LB, theta.value)

        gap = best_UB - best_LB
        UB_hist.append(best_UB)
        LB_hist.append(best_LB)
        gap_hist.append(gap)

        if k % 100 == 0:
            print(f"  k={k:4d} | UB={best_UB:.6f} | LB={best_LB:.6f} | gap={gap:.6f}")

        if gap <= tolerance:
            print(f"  -> Converged at iteration {k}!")
            break

        # ── Step 2: compute level ─────────────────────────────────────
        level = lam * best_LB + (1 - lam) * best_UB

        # ── Step 3: project onto level set ───────────────────────────
        x_var2    = cp.Variable(n)
        proj_cons = [x_var2 >= x_low, x_var2 <= x_high]
        for (fi, gi, xi) in cuts:
            proj_cons.append(fi + gi @ (x_var2 - xi) <= level)

        proj_prob = cp.Problem(cp.Minimize(cp.sum_squares(x_var2 - best_x)), proj_cons)
        proj_prob.solve(solver=cp.HIGHS)

        if proj_prob.status not in ("optimal", "optimal_inaccurate") or x_var2.value is None:
            print(f"  -> Projection infeasible at k={k}, stopping.")
            break

        x_cur = x_var2.value

        # ── update UB from the new projected point ────────────────────
        fx_cur = f(x_cur)
        if fx_cur < best_UB:
            best_UB = fx_cur
            best_x  = x_cur.copy()

        # add new cut at projected point
        cuts.append((f(x_cur), g(x_cur), x_cur.copy()))

    elapsed = time.time() - start
    historysALL[n] = {'UB': UB_hist, 'LB': LB_hist, 'Gap': gap_hist}
    results.append({
        'n': n, 'f(x*)': best_UB, 'Final Gap': gap,
        'Iterations': k, 'CPU Time (s)': elapsed
    })

# ── summary table ─────────────────────────────────────────────────────────────
df = pd.DataFrame(results)
pd.set_option('display.float_format', lambda x: '%.6f' % x)
print("\n=== Level Method Summary (Problem 4) ===")
print(df.to_string(index=False))

# ── convergence plots ─────────────────────────────────────────────────────────
fig1, axes = plt.subplots(1, len(dimensions), figsize=(20, 4))
fig1.suptitle("Level Method Convergence (UB, LB, Gap) — f(x)=||x||² on [-0.5,1]ⁿ")

for idx, n in enumerate(dimensions):
    ax   = axes[idx]
    hist = historysALL[n]
    ax.plot(hist['Gap'], color='green',   linewidth=2,    label='Gap')
    ax.plot(hist['UB'],  color='blue',    linestyle='--', label='UB')
    ax.plot(hist['LB'],  color='red',     linestyle='--', label='LB')
    ax.axhline(tolerance, color='black',  linestyle=':',  label='Tol')
    ax.set_title(f"n = {n}")
    ax.set_xlabel("Iteration k")
    ax.set_yscale('symlog')
    if idx == 0: ax.legend()

plt.tight_layout()
plt.show()

# ── scaling plots ─────────────────────────────────────────────────────────────
fig2, (ax_iter, ax_time) = plt.subplots(1, 2, figsize=(12, 4))
ns    = [r['n'] for r in results]
iters = [r['Iterations'] for r in results]
times = [r['CPU Time (s)'] for r in results]

ax_iter.plot(ns, iters, marker='o')
ax_iter.set_xscale('log'); ax_iter.set_xticks(ns); ax_iter.set_xticklabels(ns)
ax_iter.set_title("Iterations vs n"); ax_iter.set_xlabel("n"); ax_iter.set_ylabel("Iterations")

ax_time.plot(ns, times, marker='o', color='orange')
ax_time.set_xscale('log'); ax_time.set_xticks(ns); ax_time.set_xticklabels(ns)
ax_time.set_title("CPU Time vs n"); ax_time.set_xlabel("n"); ax_time.set_ylabel("Time (s)")

plt.tight_layout()
plt.show()